/** f < 0 darkens towards a cool shadow colour, f > 0 lightens towards warm white. */
export function shade(color: string, f: number): string {
  const c = hex(color);
  return f < 0 ? css(mix(c, [38, 26, 58], -f)) : css(mix(c, [255, 248, 228], f));
}

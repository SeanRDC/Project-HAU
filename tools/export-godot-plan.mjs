// Writes src/drafts/aps-godot/campus_plan.gd from the campus plan the whole
// team builds against (src/game/campus/plan.ts): every plot of the Godot layout
// (GODOT_PLOTS: buildings, covered walks, gates, ground areas) and the named
// places, in Godot world metres. Godot's world is the plan moved,
// not turned: x runs along the plan's u axis and z along v, with the origin at
// the APS entrance as before, so the APS scene keeps its coordinates.
//
//   npm run export:godot-plan
//
// Run it again whenever plan.ts or osm.ts changes. Nothing else to install:
// esbuild comes with Vite.

import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = new URL('../', import.meta.url);
const OUT = new URL('src/drafts/aps-godot/campus_plan.gd', ROOT);
const BUNDLE = new URL('builds/godot-plan.mjs', ROOT);

/**
 * Plan metres to Godot metres. The APS front (OSM v -58.4..-59.4) lands on
 * z 0.3 and the canteen wing's east wall (OSM u 38.6) on x 43.3, where the
 * Godot APS already stands.
 */
export const OFFSET = { x: 4.7, z: 58.8 };

/** Buildings the Godot scene already draws; every other one gets a reserved plot. */
const BUILT = new Set(['aps', 'chapel', 'gym', 'sjh', 'mgn', 'student', 'annex']);

await build({
  entryPoints: [fileURLToPath(new URL('src/game/campus/plan.ts', ROOT))],
  bundle: true,
  format: 'esm',
  platform: 'node',
  outfile: fileURLToPath(BUNDLE),
  logLevel: 'error',
});
const { GODOT_PLOTS, PLACES } = await import(pathToFileURL(fileURLToPath(BUNDLE)).href);

const r = (n) => Math.round(n * 10) / 10;
const v2 = (s) => `Vector2(${r(s.u + OFFSET.x)}, ${r(s.v + OFFSET.z)})`;
function centre(pts) {
  let area = 0, u = 0, v = 0;
  for (let i = 0; i < pts.length; i++) {
    const a = pts[i], b = pts[(i + 1) % pts.length];
    const k = a.u * b.v - b.u * a.v;
    area += k; u += (a.u + b.u) * k; v += (a.v + b.v) * k;
  }
  return { u: u / (3 * area), v: v / (3 * area) };
}
const quote = (s) => JSON.stringify(s);

const lines = [
  '# Generated by tools/export-godot-plan.mjs from src/game/campus/plan.ts. Do not',
  '# edit by hand: change plan.ts (or osm.ts) and run `npm run export:godot-plan`.',
  '#',
  '# Every plot on campus in Godot world metres: x along the plan\'s u, z along',
  `# its v, moved by (${OFFSET.x}, ${OFFSET.z}) so the APS entrance stays at the origin.`,
  '# Map data (c) OpenStreetMap contributors, ODbL 1.0.',
  'extends RefCounted',
  '',
  `const OFFSET := Vector2(${OFFSET.x}, ${OFFSET.z})`,
  '',
  '## id: {name, short, no, kind, outline (world x/z, closed), label (where its name goes), built}.',
  '## From the layout reference (plan.ts, GODOT_PLOTS). kind is "building", "walk" (a covered',
  '## walk), "gate" (a gate for students) or "ground" (a ground-level area). built is true for',
  '## the buildings the Godot scene draws; the rest are reserved plots.',
  'const PLOTS := {',
];
for (const [id, b] of Object.entries(GODOT_PLOTS)) {
  const pts = b.outline;
  lines.push(`\t${quote(id)}: {"name": ${quote(b.name)}, "short": ${quote(b.short)}, "no": ${b.no ?? 0}, "kind": ${quote(b.kind)}, "built": ${BUILT.has(id)},`);
  lines.push(`\t\t"label": ${v2(b.label ?? centre(pts))},`);
  lines.push(`\t\t"outline": [${pts.map(v2).join(', ')}]},`);
}
lines.push('}', '', '## Named places from the plan (gates, junctions), in world x/z.', 'const PLACES := {');
for (const [id, s] of Object.entries(PLACES)) lines.push(`\t${quote(id)}: ${v2(s)},`);
lines.push('}', '');
writeFileSync(OUT, lines.join('\n'));
console.log(`Wrote ${fileURLToPath(OUT)} (${Object.keys(GODOT_PLOTS).length} plots, ${Object.keys(PLACES).length} places)`);
